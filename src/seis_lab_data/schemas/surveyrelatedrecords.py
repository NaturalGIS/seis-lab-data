class SurveyRelatedRecordReadListItem(pydantic.BaseModel):
    id: Annotated[SurveyRelatedRecordId, pydantic.PlainSerializer(serialize_id)]
    name: DraftName
    description: DraftDescription
    status: SurveyRelatedRecordStatus
    validation_result: models.ValidationResult | None
    survey_mission: SurveyMissionReadEmbedded
    dataset_category: DatasetCategoryReadListItem | None
    workflow_stage: WorkflowStageReadListItem | None
    bbox_4326: PolygonOut | None
    temporal_extent_begin: Annotated[
        dt.date | None, pydantic.PlainSerializer(serialize_possibly_empty_date)
    ]
    temporal_extent_end: Annotated[
        dt.date | None, pydantic.PlainSerializer(serialize_possibly_empty_date)
    ]
    record_assets: list[RecordAssetReadDetailEmbedded]
    thumbnail_asset_id: (
        Annotated[RecordAssetId, pydantic.PlainSerializer(serialize_id)] | None
    )

    @classmethod
    def from_db_instance(
        cls, instance: models.SurveyRelatedRecord
    ) -> "SurveyRelatedRecordReadListItem":
        # sorted so the same thumbnail is shown across renders and the format badge
        # fed from record_assets
        assets_by_name = sorted(instance.assets, key=lambda a: (a.name, str(a.id)))
        thumbnail = next(
            (a for a in assets_by_name if AssetType.THUMBNAIL in a.asset_type), None
        )
        return cls(
            **instance.model_dump(),
            survey_mission=SurveyMissionReadEmbedded.from_db_instance(
                instance.survey_mission
            ),
            dataset_category=DatasetCategoryReadListItem.model_validate(
                instance.dataset_category, from_attributes=True
            )
            if instance.dataset_category
            else None,
            workflow_stage=WorkflowStageReadListItem.model_validate(
                instance.workflow_stage, from_attributes=True
            )
            if instance.workflow_stage
            else None,
            record_assets=[
                RecordAssetReadDetailEmbedded.model_validate(
                    db_asset, from_attributes=True
                )
                for db_asset in assets_by_name
            ],
            thumbnail_asset_id=thumbnail.id if thumbnail is not None else None,
        )


class SurveyRelatedRecordReadDetail(SurveyRelatedRecordReadListItem):
    links: list[LinkSchema] = []
    related_to_records: list[tuple[str, SurveyRelatedRecordReadEmbedded]]
    subject_for_records: list[tuple[str, SurveyRelatedRecordReadEmbedded]]
    preview_asset_id: (
        Annotated[RecordAssetId, pydantic.PlainSerializer(serialize_id)] | None
    )
    # approximated by the record's bbox, as previews do not store their own extent
    preview_bounds: PolygonOut | None

    @classmethod
    def from_db_instance(
        cls,
        instance: models.SurveyRelatedRecord,
        records_related_to: list[tuple[str, models.SurveyRelatedRecord]],
        records_subject_for: list[tuple[str, models.SurveyRelatedRecord]],
    ) -> "SurveyRelatedRecordReadDetail":
        # a record holds one derived asset per previewable data asset, taking the
        # first by name + id keeps both the thumbnail and the preview the same across
        # renders
        assets_by_name = sorted(instance.assets, key=lambda a: (a.name, str(a.id)))
        thumbnail = next(
            (a for a in assets_by_name if AssetType.THUMBNAIL in a.asset_type), None
        )
        preview = next(
            (a for a in assets_by_name if AssetType.PREVIEW in a.asset_type), None
        )
        return cls(
            **instance.model_dump(),
            survey_mission=SurveyMissionReadEmbedded.from_db_instance(
                instance.survey_mission
            ),
            dataset_category=DatasetCategoryReadListItem.model_validate(
                instance.dataset_category, from_attributes=True
            )
            if instance.dataset_category
            else None,
            workflow_stage=WorkflowStageReadListItem.model_validate(
                instance.workflow_stage, from_attributes=True
            )
            if instance.workflow_stage
            else None,
            record_assets=[
                RecordAssetReadDetailEmbedded.model_validate(
                    db_asset, from_attributes=True
                )
                for db_asset in instance.assets
            ],
            related_to_records=[
                (relation, SurveyRelatedRecordReadEmbedded.from_db_instance(record))
                for relation, record in records_related_to
            ],
            subject_for_records=[
                (relation, SurveyRelatedRecordReadEmbedded.from_db_instance(record))
                for relation, record in records_subject_for
            ],
            thumbnail_asset_id=thumbnail.id if thumbnail is not None else None,
            preview_asset_id=preview.id if preview is not None else None,
            preview_bounds=instance.bbox_4326 if preview is not None else None,
        )
