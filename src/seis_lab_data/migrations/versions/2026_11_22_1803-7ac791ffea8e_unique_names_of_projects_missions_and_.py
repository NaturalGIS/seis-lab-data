# the value of constants.NAME_MAX_LENGTH when this migration was written
_NAME_MAX_LENGTH = 100


def _rename_duplicate_names(table: str, scope_column: str | None) -> None:
    """Rename the rows of `table` whose name is already used within the same scope.

    The oldest row of each group of duplicates keeps its name, the others get the
    first free numbered name, e.g. `rev1.segy (2)`, with the name shortened to fit
    the suffix within the maximum name length. The new names are collected first
    and then applied with a single update, and a temporary index keeps the lookups
    of free names fast.
    """
    scope_columns = [scope_column] if scope_column else []
    partition = ", ".join([*scope_columns, "name"])
    scope_select = f"{scope_column}::text" if scope_column else "''"
    scope_condition = (
        f"{scope_column}::text = duplicate.scope_id AND " if scope_column else ""
    )
    op.execute(f"CREATE INDEX tmp_{table}_name_lookup ON {table} ({partition})")
    op.execute(
        f"CREATE TEMPORARY TABLE tmp_{table}_new_name "
        f"(id uuid PRIMARY KEY, scope_id text, name text) ON COMMIT DROP"
    )
    op.execute(f"CREATE INDEX ON tmp_{table}_new_name (scope_id, name)")
    op.execute(f"""
        DO $$
        DECLARE
            duplicate RECORD;
            previous_group text;
            suffix_number integer;
            candidate text;
        BEGIN
            FOR duplicate IN
                SELECT id, scope_id, name FROM (
                    SELECT
                        id,
                        {scope_select} AS scope_id,
                        name::text AS name,
                        row_number() OVER (
                            PARTITION BY {partition} ORDER BY created_at, id
                        ) AS position
                    FROM {table}
                ) AS ranked
                WHERE position > 1
                ORDER BY scope_id, name, position
            LOOP
                -- the numbers of a group only grow, the search resumes from the last one
                IF previous_group IS DISTINCT FROM duplicate.scope_id || '/' || duplicate.name THEN
                    previous_group := duplicate.scope_id || '/' || duplicate.name;
                    suffix_number := 1;
                END IF;
                LOOP
                    suffix_number := suffix_number + 1;
                    candidate := left(
                        duplicate.name,
                        {_NAME_MAX_LENGTH} - length(' (' || suffix_number || ')')
                    ) || ' (' || suffix_number || ')';
                    -- shortened names of different groups may end up alike
                    EXIT WHEN NOT EXISTS (
                        SELECT 1 FROM {table}
                        WHERE {scope_condition}name = candidate
                    ) AND NOT EXISTS (
                        SELECT 1 FROM tmp_{table}_new_name AS new_name
                        WHERE new_name.scope_id = duplicate.scope_id
                        AND new_name.name = candidate
                    );
                END LOOP;
                INSERT INTO tmp_{table}_new_name
                VALUES (duplicate.id, duplicate.scope_id, candidate);
            END LOOP;
        END
        $$
    """)
    op.execute(f"""
        UPDATE {table} SET name = new_name.name
        FROM tmp_{table}_new_name AS new_name
        WHERE {table}.id = new_name.id
    """)
    op.execute(f"DROP INDEX tmp_{table}_name_lookup")


